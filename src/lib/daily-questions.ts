export function questionById(id: string) {
  return DAILY_QUESTIONS.find((q) => q.id === id) ?? DAILY_QUESTIONS[0];
}

export function dayIndex(dateIso: string) {
  const [y, m, d] = dateIso.split("-").map(Number);
  const start = Date.UTC(y, 0, 0);
  const now = Date.UTC(y, m - 1, d);
  return Math.round((now - start) / 86400000);
}

export function pickQuestion(dateIso: string, skipIds: string[]) {
  const n = DAILY_QUESTIONS.length;
  const start = Math.max(0, (dayIndex(dateIso) - 1) % n);
  for (let step = 0; step < n; step++) {
    const q = DAILY_QUESTIONS[(start + step) % n];
    if (!skipIds.includes(q.id)) return q;
  }
  return DAILY_QUESTIONS[start];
}
